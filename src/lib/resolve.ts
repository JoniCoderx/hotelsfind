import { destinations, type Destination } from '../data/destinations';
import cityFile from '../data/agoda-cities.json';

/** Find one of our destinations from a free-text query (Hebrew or English) or slug. */
export function findDestination(input: { slug?: string | null; q?: string | null; d?: string | null }): Destination | undefined {
  if (input.slug) {
    const bySlug = destinations.find((x) => x.slug === input.slug);
    if (bySlug) return bySlug;
  }
  const he = (input.d || '').trim();
  const en = (input.q || '').trim().toLowerCase();
  return destinations.find(
    (x) =>
      (he && (x.he === he || he.includes(x.he))) ||
      (en && (x.en.toLowerCase() === en || x.en.split(',')[0].toLowerCase() === en.split(',')[0].trim())),
  );
}

/**
 * Agoda city ID for a destination. Sources, in priority order:
 * 1. AGODA_CITY_IDS env var, JSON like {"eilat": 12345} (no redeploy of code needed)
 * 2. src/data/agoda-cities.json, generated by `npm run agoda:cities`
 * 3. agodaCityId in src/data/destinations.ts
 */
export function agodaCityId(d: Destination): number | undefined {
  let env: Record<string, number> = {};
  try {
    env = JSON.parse(process.env.AGODA_CITY_IDS || '{}');
  } catch {
    // Ignore a malformed override rather than failing every search.
  }
  const file = cityFile as Record<string, number>;
  return Number(env[d.slug]) || Number(file[d.slug]) || d.agodaCityId;
}
