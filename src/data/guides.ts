// Hotel guides: one practical question per page ("where to stay in Athens", "Eilat with kids").
// General, durable advice only: no prices, no rankings, no claims about specific hotels.

export interface GuideSection {
  h: string;
  p?: string[];
  /** Destination slugs shown as cards (multi-destination guides). */
  dests?: string[];
  /** Named items are areas (shown as cards, `tag` = who it suits); unnamed items are tips. */
  list?: { name?: string; text: string; tag?: string }[];
}

export interface Guide {
  slug: string;
  /** Destination slug: the guide's photo, search links and "more about" link come from it.
   *  Multi-destination guides leave it out and list their places in sections' `dests`. */
  dest?: string;
  /** Where the quick search goes when the guide has no destination page (or a narrower place). */
  place?: { he: string; en: string };
  /** Hero photo, when the destination's own photo doesn't fit the topic. */
  photo?: Photo;
  /** Page heading. */
  title: string;
  /** <title> tag, before " | מלונזול". */
  seoTitle: string;
  description: string;
  lead: string;
  /** "In short": three one-line answers shown first: where to stay, when, the one thing to check. */
  glance: { where: string; when: string; key: string };
  /** Months (1–12) shown on the season strip: best balance of weather and price, and the busiest. */
  season?: { best: number[]; busy: number[] };
  /** Month the guide was last checked, shown under the title (e.g. 'אוקטובר 2026'). */
  updated?: string;
  sections: GuideSection[];
  /** Short checklist shown in a box before booking. */
  checklist: string[];
  faq: { q: string; a: string }[];
}

